// Helper untuk mengambil event berdasarkan tanggal
export function getEventsForDate(dateStr) {
  // dateStr format: 'YYYY-MM-DD' atau angka hari
  if (!dateStr) return []
  if (typeof dateStr === 'number') {
    const dayPadded = String(dateStr).padStart(2, '0')
    const key = `2026-10-${dayPadded}`
    return calendarEventsData[key] || []
  }
  return calendarEventsData[dateStr] || []
}

// Helper untuk format teks tanggal Indonesia
export function formatIndonesianDate(day, month = 9, year = 2026) {
  // month is 0-indexed (9 = Oktober)
  const monthNames = [
    'Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni',
    'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember'
  ]
  const dayNames = ['Minggu', 'Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu']
  const dateObj = new Date(year, month, day)
  const dayName = dayNames[dateObj.getDay()]
  return `${dayName}, ${day} ${monthNames[month]} ${year}`
}
